final _iso2 = {for (final entry in kIso6391To6392.entries) entry.value: entry.key};
final _codes = {
  ..._iso2,
  for (final code in _names.keys) code: code,
  for (final entry in _names.entries) entry.value.toLowerCase(): entry.key,
  for (final entry in kIso6392Languages.entries) entry.value.toLowerCase(): _iso2[entry.key] ?? entry.key,
  '英语': 'en', '英文': 'en', '日文': 'ja', '国语': 'zh', '繁体中文': 'zh', '简体中文': 'zh',
  '繁體中文': 'zh', '簡體中文': 'zh', 'chs': 'zh', 'cht': 'zh', 'cmn': 'zh', 'yue': 'yue', '粤语': 'yue',
};
final _languageSeparator = RegExp(r'[\s_·(\[-]+');
final _traditional = RegExp(r'\b(?:hant|cht|tw|hk|traditional)\b|繁[体體]');
final _simplified = RegExp(r'\b(?:hans|chs|cn|sg|simplified)\b|[简簡][体體]');

String? _languageCode(String? input) {
  final text = input?.trim().toLowerCase() ?? '';
  if (text.isEmpty || text == 'und') return null;
  final primary = text.split(_languageSeparator).first;
  return _codes[text] ?? _codes[primary] ?? _codes[toIso3Language(primary)];
}

String? _chineseScript(String value) {
  final hint = value.toLowerCase().replaceAll('_', '-');
  if (_traditional.hasMatch(hint)) return '繁体中文';
  if (_simplified.hasMatch(hint)) return '简体中文';
  return null;
}

/// The stream language identifies the track. Its title may distinguish
/// Chinese scripts when both streams share the same ISO language.
({String? code, String title, String badge}) evTrackLanguage(String? language, String name) {
  final code = _languageCode(language) ?? _languageCode(name);
  if (code == 'zh') {
    return (code: code, title: _chineseScript(language ?? '') ?? _chineseScript(name) ?? '中文', badge: '中');
  }
  if (code == 'yue') return (code: code, title: '粤语', badge: '粤');
  if (code != null) {
    return (code: code, title: _names[code] ?? code.toUpperCase(), badge: code == 'ja' ? '日' : code.toUpperCase());
  }
  final fallback = name.split(' (').first.trim();
  final generic = const {'', 'subtitle', 'und', 'unknown', 'undefined', 'undetermined'}.contains(fallback.toLowerCase());
  return (code: null, title: generic ? '未标明语言' : fallback, badge: '—');
}
