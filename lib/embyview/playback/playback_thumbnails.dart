class PlaybackThumbnails {
  PlaybackThumbnails(this.client, this.scope);
  final MediaServerClient client;
  final String scope;
  TrickplayInfo? _info;
  String? _item;
  String? _source;
  int _load = 0;
  Future<void> load(String item, String source, Map<String, dynamic> raw) async {
    final load = ++_load;
    _info = null;
    _item = item;
    _source = source;
    await mergeServerTrickplay(client, item, raw, source);
    var info = TrickplayInfo.fromItemData(raw, mediaSourceId: source);
    if (info == null && client.trickplayApi != null) {
      try {
        final set = await client.trickplayApi!.getThumbnailSet(item, width: 320, mediaSourceId: source);
        if (set?.isValid == true) {
          info = TrickplayInfo.fromThumbnailSet(set!, width: 320);
        }
      } catch (_) {
        /* Optional seek previews do not fail playback. */
      }
    }
    if (load == _load) _info = info?.isValid == true ? info : null;
  }

  void clear() {
    _load++;
    _info = null;
    _item = null;
    _source = null;
  }

  ThumbnailFrame? at(Duration position) {
    final info = _info;
    final item = _item;
    if (info == null || item == null) return null;
    final tile = info.resolveTile(position < Duration.zero ? Duration.zero : position);
    final url = info.usesIndividualFrames
        ? client.trickplayApi?.getFrameImageUrl(
            item,
            width: info.width,
            positionTicks: tile.positionTicks!,
            imageTag: tile.imageTag!,
            mediaSourceId: _source,
          )
        : client.imageApi.getTrickplayTileImageUrl(
            item,
            width: info.width,
            index: tile.imageIndex,
            mediaSourceId: _source,
          );
    if (url == null) return null;
    final token = client.accessToken;
    final headers = <String, String>{};
    if (token != null) {
      headers['X-Emby-Token'] = token;
    }
    final image = _ThumbnailImage(
      Uri.parse(url),
      headers,
      tile.sourceRect,
      '$scope:$item:$_source:${tile.imageIndex}:${tile.sourceRect}',
    );
    return ThumbnailFrame(
      image: _ThumbnailArtwork(image, info.width, info.height),
      position: tile.positionTicks != null
          ? Duration(microseconds: tile.positionTicks! ~/ 10)
          : Duration(milliseconds: (position.inMilliseconds ~/ info.interval) * info.interval),
    );
  }
}

class _ThumbnailArtwork implements ArtworkRef {
  const _ThumbnailArtwork(this._image, this.width, this.height);
  final _ThumbnailImage _image;
  @override
  final int width;
  @override
  final int height;
  @override
  String get id => _image.cacheKey;
  @override
  String get cacheKey => _image.cacheKey;
  @override
  double get aspectRatio => width / height;
  @override
  ImageProvider<Object> get image => _image;
}

/// A frame capability crops a sprite inside the image provider, so pages only
/// receive a normal authorized image, including for servers using tiled BIFs.
class _ThumbnailImage extends ImageProvider<Object> {
  const _ThumbnailImage(this.uri, this.headers, this.rect, this.cacheKey);
  final Uri uri;
  final Map<String, String> headers;
  final ui.Rect rect;
  final String cacheKey;
  @override
  Future<Object> obtainKey(ImageConfiguration configuration) => SynchronousFuture(this);
  @override
  ImageStreamCompleter loadImage(Object key, ImageDecoderCallback decode) =>
      OneFrameImageStreamCompleter(_load());
  Future<ImageInfo> _load() async {
    final client = HttpClient();
    ui.Codec? codec;
    ui.Image? sheet;
    try {
      final request = await client.getUrl(uri);
      headers.forEach(request.headers.set);
      // Every image URL is generated by the authenticated Emby API. Follow no
      // redirects carrying its token; a missing preview uses the UI fallback.
      request.followRedirects = false;
      final response = await request.close();
      if (response.statusCode != 200) {
        throw const HttpException('Preview unavailable');
      }
      final bytes = await consolidateHttpClientResponseBytes(response);
      codec = await ui.instantiateImageCodec(bytes);
      sheet = (await codec.getNextFrame()).image;
      final recorder = ui.PictureRecorder();
      final canvas = ui.Canvas(recorder);
      canvas.drawImageRect(sheet, rect, ui.Rect.fromLTWH(0, 0, rect.width, rect.height), ui.Paint());
      final picture = recorder.endRecording();
      final image = await picture.toImage(rect.width.toInt(), rect.height.toInt());
      picture.dispose();
      return ImageInfo(image: image);
    } finally {
      sheet?.dispose();
      codec?.dispose();
      client.close(force: true);
    }
  }

  @override
  bool operator ==(Object other) => other is _ThumbnailImage && cacheKey == other.cacheKey;
  @override
  int get hashCode => cacheKey.hashCode;
}
